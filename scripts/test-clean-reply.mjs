/**
 * test-clean-reply.mjs — 微信回复去乱码与句末去多余括号专项自动化验收测试
 *
 * 验收场景：
 *  1. 句末孤立左括号剥离（如 "嗯？怎么了？(" -> "嗯？怎么了？"）
 *  2. 句末孤立右括号剥离（如 "你是不是又在搞什么鬼？)" -> "你是不是又在搞什么鬼？"）
 *  3. 句末带句号的孤立括号与句号一并消除（如 "哼，算你识相。(" -> "哼，算你识相"）
 *  4. 句末带句号的未闭合右括号消除（如 "今天确实有事，不跟你瓦了。)" -> "今天确实有事，不跟你瓦了"）
 *  5. 整句外层包裹括号解包（如 "(我知道了)" -> "我知道了", "（没问题）" -> "没问题"）
 *  6. 多气泡切分畸形括号连发处理（如 "气泡1( ||| 气泡2)" -> ["气泡1", "气泡2"]）
 *  7. 多气泡外包括号深度解包（如 "(气泡1 (||| 气泡2))" -> ["气泡1", "气泡2"]）
 *  8. 动作与心理神态括号描述清洗（如 "(翻白眼)", "（傲娇转头）"）
 *  9. 正文合法成对括号保持完整（如 "推荐玩（黑神话）挺好" -> 保持）
 * 10. 乱码与不可见控制字符清洗（\uFFFD, \u200B, \x00-\x1F, ANSI 码）
 * 11. 孤立代理对 (Lone Surrogates) 安全规整
 * 12. 句末真人微信打字留白（剥除死板句号）
 *
 * 用法：node scripts/test-clean-reply.mjs
 */

import { cleanBubbleText, splitBubbles } from '../src/utils.js'

let pass = 0
let fail = 0
const ok = (name, cond, detail = '') => {
  console.log(`${cond ? '✅ PASS' : '❌ FAIL'}  ${name}${detail ? ' → ' + detail : ''}`)
  cond ? pass++ : fail++
}

console.log('==================================================')
console.log('  微信回复去乱码与句末去多余括号专项验收')
console.log('==================================================')

// 1. 句末孤立左括号
ok('句末孤立左括号消除', cleanBubbleText('嗯？怎么了？(') === '嗯？怎么了？')
ok('句末全角孤立左括号消除', cleanBubbleText('在吗？（') === '在吗？')
ok('句末方括号消除', cleanBubbleText('收到消息【') === '收到消息')

// 2. 句末未配对孤立右括号
ok('句末孤立英文右括号消除', cleanBubbleText('你是不是又在搞什么鬼？)') === '你是不是又在搞什么鬼？')
ok('句末孤立中文全角右括号消除', cleanBubbleText('今天不去了）') === '今天不去了')
ok('句末多层孤立右括号消除', cleanBubbleText('好嘛））') === '好嘛')

// 3. 句末带句号的孤立括号与句号一体消除
ok('句末。( 复合符号消除', cleanBubbleText('哼，算你识相。(') === '哼，算你识相')
ok('句末。（ 复合符号消除', cleanBubbleText('哼，算你识相。（') === '哼，算你识相')
ok('句末。) 复合符号消除', cleanBubbleText('今天确实有事，不跟你瓦了。)') === '今天确实有事，不跟你瓦了')
ok('句末。） 复合符号消除', cleanBubbleText('今天确实有事，不跟你瓦了。）') === '今天确实有事，不跟你瓦了')

// 4. 整句外层成对包裹解包
ok('整句半角小括号解包', cleanBubbleText('(好的我知道了)') === '好的我知道了')
ok('整句全角小括号解包', cleanBubbleText('（网卡了，稍等再发一遍？）') === '网卡了，稍等再发一遍？')
ok('整句方括号解包', cleanBubbleText('【收到啦】') === '收到啦')

// 5. 动作与心理神态括号描写消除
ok('消除句末动作标注 (翻白眼)', cleanBubbleText('哼，才没有(翻白眼)') === '哼，才没有')
ok('消除句首/句中动作标注 （转头）', cleanBubbleText('（转头）谁稀罕理你') === '谁稀罕理你')
ok('消除截断未闭合的动作标注', cleanBubbleText('知道了啦（傲娇') === '知道了啦')

// 6. 保护正文合法的成对括号
ok('正文中合法的全角括号保留', cleanBubbleText('我玩的是（黑神话悟空）很不错') === '我玩的是（黑神话悟空）很不错')
ok('正文中合法的半角括号保留', cleanBubbleText('当前版本是 Node.js (v18.20) 环境') === '当前版本是 Node.js (v18.20) 环境')

// 7. 多气泡连发中的括号畸形彻底拆解与净化
const bubbles1 = splitBubbles('嗯？怎么了？( ||| 你是不是又在搞什么鬼？)')
ok('多气泡连发带孤立括号拆解成功', bubbles1.length === 2 && bubbles1[0] === '嗯？怎么了？' && bubbles1[1] === '你是不是又在搞什么鬼？')

const bubbles2 = splitBubbles('(哼，算你识相。(|||今天确实有事，不跟你瓦了。))')
ok('多气泡连发外层包裹与内联括号全消除', bubbles2.length === 2 && bubbles2[0] === '哼，算你识相' && bubbles2[1] === '今天确实有事，不跟你瓦了')

const bubbles3 = splitBubbles('缺人？(|||你朋友要是肯来，我倒是可以考虑。)')
ok('实测高频缺陷缺人连发拆分净化', bubbles3.length === 2 && bubbles3[0] === '缺人？' && bubbles3[1] === '你朋友要是肯来，我倒是可以考虑')

// 8. 乱码、控制字符与孤立代理对清洗
ok('Unicode 替换字符 \\uFFFD 清除', cleanBubbleText('测试\uFFFD内容') === '测试内容')
ok('不可见零宽字符与 BOM 清除', cleanBubbleText('微信\u200B\uFEFF消息') === '微信消息')
ok('ASCII 控制字符清除', cleanBubbleText('你好\x00\x07\x1B[31m世界\x1F') === '你好世界')
ok('孤立代理对安全处理（不抛异常且无乱码）', cleanBubbleText('前缀\uD800后缀') === '前缀后缀')
ok('正常 Emoji 完整保留', cleanBubbleText('哈哈😄👍🐟') === '哈哈😄👍🐟')

// 9. 句末死板句号消除
ok('句末死板句号留白', cleanBubbleText('好，我知道了。') === '好，我知道了')

console.log('\n==================================================')
console.log(`去乱码与去括号专项统计: ${pass} 通过 / ${fail} 失败`)
console.log('==================================================')

if (fail > 0) {
  process.exit(1)
}
